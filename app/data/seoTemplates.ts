// 문자열을 고유 정수로 변환하는 해시 함수 (페이지별로 고유한 순번이 안정적으로 유지됨)
function getHashCode(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

// 60가지 타이틀 순차 로테이션 추출
export function getRotatedTitle(locationName: string): string {
  const hash = getHashCode(locationName);
  const index = hash % titleTemplates.length; // 0 ~ 59 순환
  return titleTemplates[index].replaceAll("{loc}", locationName);
}

